function htmlEscape(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}
function renderEditorial(e: Editorial): string {
  return [
    `<h2>${htmlEscape(e.heading)}</h2>`,
    `<p>${htmlEscape(e.opening)}</p>`,
    '<h3>Đặc điểm và tính chất</h3>',
    `<p>${htmlEscape(e.features)}</p>`,
    '<h3>Khi nào nên cân nhắc?</h3>',
    `<p>${htmlEscape(e.application)}</p>`,
    '<h3>Kiểm tra trước khi lắp</h3>',
    `<p>${htmlEscape(e.fit)}</p>`,
    `<p><strong>${htmlEscape(e.closing)}</strong></p>`,
  ].join('\n');
}
function summary(e: Editorial): string {
  // Use the editorial's own first paragraph rather than a generic product template.
  const sentences = e.opening.split(/(?<=[.!?])\s+/);
  return (sentences.length > 1 ? sentences.slice(0,2).join(' ') : e.opening).slice(0,290);
}

